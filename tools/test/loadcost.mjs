import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=vulkan', '--enable-features=Vulkan'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send('Network.enable');
let bytes = 0; const byType = {};
cdp.on('Network.loadingFinished', (e) => { bytes += e.encodedDataLength; });
const reqs = new Map();
cdp.on('Network.responseReceived', (e) => { reqs.set(e.requestId, e.response.url); });
cdp.on('Network.loadingFinished', (e) => { const u = reqs.get(e.requestId) || ''; const ext = (u.split('?')[0].split('.').pop() || 'other'); byType[ext] = (byType[ext] || 0) + e.encodedDataLength; });
const t0 = Date.now();
await page.goto(process.env.URL || 'http://localhost:4317/games/novaki/');
await page.waitForFunction(() => window.NOVAKI_QA, null, { timeout: 30000 });
const ready = Date.now() - t0;
await page.waitForTimeout(1500);
console.log('ready in', ready, 'ms; transferred until title:', (bytes / 1048576).toFixed(2), 'MB');
console.log(Object.entries(byType).map(([k, v]) => `${k}: ${(v / 1024).toFixed(0)}KB`).join(', '));
await browser.close();
