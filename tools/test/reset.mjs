import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=vulkan', '--enable-features=Vulkan'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.addInitScript(() => { if (!sessionStorage.getItem('x')) { sessionStorage.setItem('x', '1'); localStorage.setItem('novaki-strike-twice-save-v1', JSON.stringify({ coins: 555, seenIntro: true, shop: { hp: 2 }, settings: { music: 0.3 } })); } });
await page.goto(process.env.URL || 'http://localhost:4317/games/novaki/');
await page.waitForFunction(() => window.NOVAKI_QA, null, { timeout: 30000 });
const click = async (t) => { await page.waitForTimeout(350); await page.locator('.screen.show button:visible', { hasText: t }).first().click(); };
console.log('before', JSON.stringify((await page.evaluate(() => window.NOVAKI_QA.state())).meta.currency));
await page.keyboard.press('Enter');
await click('Settings');
await click('Reset Progress');
console.log('armed label:', await page.locator('.screen.show button:visible', { hasText: 'Really' }).count());
await click('Really');
const s = await page.evaluate(() => ({ coins: window.NOVAKI_QA.state().meta.currency, shop: window.NOVAKI_QA.state().meta.shop, raw: localStorage.getItem('novaki-strike-twice-save-v1') }));
console.log('after', JSON.stringify(s).slice(0, 200));
await page.reload();
await page.waitForFunction(() => window.NOVAKI_QA, null, { timeout: 30000 });
console.log('after reload', (await page.evaluate(() => window.NOVAKI_QA.state())).meta.currency);
console.log('ERRORS', errors.join('\n'));
await browser.close();
