import { chromium } from 'playwright';
const OUT = process.env.OUT;
const browser = await chromium.launch({ args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=vulkan', '--enable-features=Vulkan'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.addInitScript(() => localStorage.setItem('novaki-strike-twice-save-v1', JSON.stringify({ seenIntro: true, seen: ['mold', 'moth'] })));
await page.goto(process.env.URL || 'http://localhost:4317/games/novaki/');
await page.waitForFunction(() => window.NOVAKI_QA, null, { timeout: 30000 });
const click = async (t) => { await page.waitForTimeout(350); await page.locator('.screen.show button:visible', { hasText: t }).first().click(); };
await page.keyboard.press('Enter');
await click('How to Play'); await click('Bestiary'); await page.waitForTimeout(400);
await page.screenshot({ path: OUT + '/bestiary_fresh.png' });
await click('Back'); await click('Play'); await page.waitForTimeout(500);
await page.screenshot({ path: OUT + '/loadout_daily.png' });
await click('Play Daily'); await page.waitForTimeout(1500);
const s = await page.evaluate(() => { const g = window.__novaki.game; return { screen: window.NOVAKI_QA.state().screen, seed: g.seed, daily: g.daily, weapon: g.player.weapons[0].id }; });
console.log(JSON.stringify(s));
await page.keyboard.press('Escape'); await page.waitForTimeout(500);
await click('Restart'); await page.waitForTimeout(1200);
const s2 = await page.evaluate(() => { const g = window.__novaki.game; return { screen: window.NOVAKI_QA.state().screen, seed: g.seed, daily: g.daily, time: g.time }; });
console.log('after restart', JSON.stringify(s2));
await page.screenshot({ path: OUT + '/title_embers.png' });
console.log('ERRORS', errors.join('\n'));
await browser.close();
